export function getPostBySlug(slug: string): BlogPost | undefined {
  return POSTS.find((p) => p.id === slug);
}

export function getRelatedPosts(current: BlogPost, count = 3): BlogPost[] {
  const sameCat = POSTS.filter((p) => p.id !== current.id && p.cat === current.cat);
  const others = POSTS.filter((p) => p.id !== current.id && p.cat !== current.cat);
  return [...sameCat, ...others].slice(0, count);
}

export function getAdjacentPosts(current: BlogPost): {
  prev: BlogPost | null;
  next: BlogPost | null;
} {
  const idx = POSTS.findIndex((p) => p.id === current.id);
  return {
    prev: idx > 0 ? POSTS[idx - 1] : null,
    next: idx < POSTS.length - 1 ? POSTS[idx + 1] : null,
  };
}
